#!/usr/bin/env node

/**
 * Advanced iconMap.ts cleaner - removes Mac OS X metadata, validates SVG content,
 * and provides comprehensive statistics
 */

const fs = require('fs');
const path = require('path');

console.log('🧹 Starting advanced iconMap cleaning process...');

const iconMapPath = path.join(__dirname, '..', 'iconMap.ts');
const backupPath = iconMapPath + '.backup.' + Date.now();

// Create backup
console.log('📋 Creating backup...');
const originalContent = fs.readFileSync(iconMapPath, 'utf8');
fs.writeFileSync(backupPath, originalContent);
console.log(`✅ Backup created: ${backupPath}`);

// Extract iconMap content
const iconMapMatch = originalContent.match(/export const iconMap: Record<string, string> = \{([\s\S]*?)\};/);
if (!iconMapMatch) {
  console.error('❌ Could not find iconMap in file');
  process.exit(1);
}

const iconMapContent = iconMapMatch[1];
console.log('📊 Parsing icon entries...');

// Parse entries more robustly
const entries = [];
let currentEntry = '';
let inString = false;
let braceDepth = 0;
let i = 0;

while (i < iconMapContent.length) {
  const char = iconMapContent[i];
  
  if (char === '"' && iconMapContent[i-1] !== '\\') {
    inString = !inString;
  }
  
  if (!inString) {
    if (char === '{') braceDepth++;
    if (char === '}') braceDepth--;
    
    if (char === ',' && braceDepth === 0) {
      if (currentEntry.trim()) {
        entries.push(currentEntry.trim());
      }
      currentEntry = '';
      i++;
      continue;
    }
  }
  
  currentEntry += char;
  i++;
}

// Add the last entry if it exists
if (currentEntry.trim()) {
  entries.push(currentEntry.trim());
}

console.log(`📈 Found ${entries.length} total entries`);

// Enhanced filtering with detailed statistics
let stats = {
  total: entries.length,
  macOSCorrupted: 0,
  tooShort: 0,
  noSvgTag: 0,
  invalidViewBox: 0,
  malformedStroke: 0,
  duplicates: 0,
  valid: 0
};

const validEntries = [];
const seenKeys = new Set();

entries.forEach((entry, index) => {
  const keyMatch = entry.match(/^"([^"]+)":/);
  if (!keyMatch) {
    return; // Skip malformed entries
  }
  
  const key = keyMatch[1];
  const valueMatch = entry.match(/^"[^"]+"\s*:\s*`([^`]+)`/);
  if (!valueMatch) {
    return; // Skip entries without proper template literal values
  }
  
  const value = valueMatch[1];
  
  // Check for duplicates
  if (seenKeys.has(key)) {
    stats.duplicates++;
    return;
  }
  seenKeys.add(key);
  
  // Filter Mac OS X metadata
  if (value.includes('Mac OS X') || 
      value.includes('ATTR') || 
      value.includes('com.apple.quarantine') ||
      value.includes('__MACOSX') ||
      value.includes('.DS_Store')) {
    stats.macOSCorrupted++;
    return;
  }
  
  // Check minimum length
  if (value.length < 50) {
    stats.tooShort++;
    return;
  }
  
  // Check for SVG tags
  if (!value.includes('<svg') || !value.includes('</svg>')) {
    stats.noSvgTag++;
    return;
  }
  
  // Check for common viewBox issues
  if (value.includes('viewBox="0 0 2000 2000"')) {
    stats.invalidViewBox++;
  }
  
  // Check for malformed stroke attributes
  if (value.includes('stroke-') && !value.includes('stroke-width') && !value.includes('stroke-linecap') && !value.includes('stroke-linejoin')) {
    stats.malformedStroke++;
  }
  
  validEntries.push(entry);
  stats.valid++;
});

// Generate cleaned content
const cleanedContent = `// Auto-generated by SVG → TS Map
export const iconMap: Record<string, string> = {
${validEntries.join(',\n')}
};`;

// Write cleaned file
fs.writeFileSync(iconMapPath, cleanedContent);

// Calculate file sizes
const originalSize = (originalContent.length / 1024 / 1024).toFixed(2);
const cleanedSize = (cleanedContent.length / 1024 / 1024).toFixed(2);
const reduction = (((originalContent.length - cleanedContent.length) / originalContent.length) * 100).toFixed(1);

// Report comprehensive statistics
console.log('\n📊 CLEANING STATISTICS:');
console.log('='.repeat(50));
console.log(`📊 Total entries processed: ${stats.total}`);
console.log(`✅ Valid entries retained: ${stats.valid}`);
console.log(`🗑️  Mac OS X corrupted: ${stats.macOSCorrupted}`);
console.log(`📏 Too short (< 50 chars): ${stats.tooShort}`);
console.log(`🏷️  Missing SVG tags: ${stats.noSvgTag}`);
console.log(`👁️  Invalid viewBox (2000x2000): ${stats.invalidViewBox}`);
console.log(`✏️  Malformed stroke attributes: ${stats.malformedStroke}`);
console.log(`🔁 Duplicate keys: ${stats.duplicates}`);
console.log('\n📁 FILE STATISTICS:');
console.log('='.repeat(50));
console.log(`📦 Original size: ${originalSize} MB`);
console.log(`✨ Cleaned size: ${cleanedSize} MB`);
console.log(`💾 Size reduction: ${reduction}%`);

// Quality assessment
const recoveryRate = (stats.valid / stats.total * 100).toFixed(1);
console.log(`\n🎯 Recovery rate: ${recoveryRate}%`);

if (recoveryRate > 80) {
  console.log('🎉 EXCELLENT recovery! Most icons preserved.');
} else if (recoveryRate > 60) {
  console.log('✅ GOOD recovery! Majority of icons preserved.');
} else if (recoveryRate > 40) {
  console.log('⚠️  MODERATE recovery. Some icons lost but core functionality intact.');
} else {
  console.log('❌ POOR recovery. Consider investigating data source.');
}

console.log('\n✅ Advanced iconMap cleaning completed successfully!');