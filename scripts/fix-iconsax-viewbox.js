#!/usr/bin/env node

const fs = require('fs');
const path = require('path');

console.log('🔧 Fixing Iconsax viewBox and cleaning corrupted entries...');

// Create backup
const iconMapPath = path.join(__dirname, '..', 'iconMap.ts');
const backupPath = `${iconMapPath}.backup-${Date.now()}`;
fs.copyFileSync(iconMapPath, backupPath);
console.log(`📦 Backup created: ${backupPath}`);

// Read the file
const content = fs.readFileSync(iconMapPath, 'utf8');

// Extract the iconMap object content
const iconMapMatch = content.match(/export const iconMap: Record<string, string> = \{([\s\S]*)\};/);
if (!iconMapMatch) {
  console.error('❌ Could not find iconMap object in file');
  process.exit(1);
}

const iconMapContent = iconMapMatch[1];

// Parse entries more robustly
const entries = [];
let currentEntry = '';
let inString = false;
let braceCount = 0;
let quoteChar = null;
let i = 0;

while (i < iconMapContent.length) {
  const char = iconMapContent[i];
  const prevChar = i > 0 ? iconMapContent[i - 1] : '';
  
  if (!inString) {
    if (char === '"' || char === '`') {
      inString = true;
      quoteChar = char;
    } else if (char === '{') {
      braceCount++;
    } else if (char === '}') {
      braceCount--;
    } else if (char === ',' && braceCount === 0) {
      if (currentEntry.trim()) {
        entries.push(currentEntry.trim());
      }
      currentEntry = '';
      i++;
      continue;
    }
  } else {
    if (char === quoteChar && prevChar !== '\\') {
      inString = false;
      quoteChar = null;
    }
  }
  
  currentEntry += char;
  i++;
}

// Don't forget the last entry
if (currentEntry.trim()) {
  entries.push(currentEntry.trim());
}

console.log(`📊 Found ${entries.length} total entries`);

// Filter and fix entries
const cleanedEntries = [];
let removedCorrupted = 0;
let fixedViewBox = 0;

for (const entry of entries) {
  if (!entry.includes(':')) continue;
  
  const [keyPart, ...valueParts] = entry.split(':');
  const key = keyPart.trim().replace(/['"]/g, '');
  const value = valueParts.join(':').trim();
  
  // Skip corrupted entries
  if (value.includes('Mac OS X') || 
      value.includes('__MACOSX') || 
      value.includes('ATTR') || 
      value.includes('com.apple.quarantine') ||
      value.includes('.DS_Store') ||
      value.length < 50 ||
      !value.includes('<svg') ||
      !value.includes('</svg>')) {
    removedCorrupted++;
    continue;
  }
  
  // Fix viewBox issues for valid SVGs
  let fixedValue = value;
  if (fixedValue.includes('viewBox="0 0 2000 2000"')) {
    fixedValue = fixedValue.replace(/viewBox="0 0 2000 2000"/g, 'viewBox="0 0 24 24"');
    fixedViewBox++;
  }
  
  // Ensure width and height are 24
  if (!fixedValue.includes('width="24"') || !fixedValue.includes('height="24"')) {
    fixedValue = fixedValue.replace(/width="[^"]*"/g, 'width="24"');
    fixedValue = fixedValue.replace(/height="[^"]*"/g, 'height="24"');
    
    // If no width/height found, add them
    if (!fixedValue.includes('width=') || !fixedValue.includes('height=')) {
      fixedValue = fixedValue.replace('<svg', '<svg width="24" height="24"');
    }
  }
  
  cleanedEntries.push(`  "${key}": ${fixedValue}`);
}

// Write cleaned content
const newContent = `// Auto-generated by SVG → TS Map
export const iconMap: Record<string, string> = {
${cleanedEntries.join(',\n')}
};
`;

fs.writeFileSync(iconMapPath, newContent, 'utf8');

console.log(`✅ Cleaning complete!
📊 Statistics:
  - 🗑️ Removed corrupted entries: ${removedCorrupted}
  - 🔧 Fixed viewBox entries: ${fixedViewBox}
  - ✅ Valid entries remaining: ${cleanedEntries.length}
  - 💾 Total size: ${Math.round(fs.statSync(iconMapPath).size / 1024)}KB
  
🎉 Iconsax icons should now display properly!`);